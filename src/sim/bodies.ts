const BY_ID = new Map(BODIES.map((b) => [b.id, b]));

export function getBody(id: string): BodyDef | undefined {
  return BY_ID.get(id);
}

export function bodyElements(id: string, tDays: number): Elements | null {
  const b = BY_ID.get(id);
  if (!b || b.group === "sun") return null;
  return elementsAtTime(baseElements(b), tDays);
}

export function teqOf(b: BodyDef): number {
  if (b.surfaceTempK && b.id === "sun") return b.surfaceTempK;
  return equilibriumK(b.albedo, b.starL, Math.max(b.aAU, 0.00465));
}

export function displayTemp(b: BodyDef): number {
  return b.surfaceTempK ?? teqOf(b);
}

export function gOf(b: BodyDef): number {
  return gravityMs2(b.massKg, b.radiusKm);
}

